"""Build compact, offline OpenType Thai shaping and antialiased glyph tables.

pip install uharfbuzz freetype-py fonttools pillow
Font source: Google Fonts Sarabun, SIL OFL 1.1 (firmware/fonts/OFL.txt).
HarfBuzz does GSUB/GPOS, mark/mkmk positioning and SARA AM decomposition on
the host. The ESP32 only looks up complete orthographic clusters; no TTF,
framebuffer, PSRAM, network, or SD card is needed to display Thai.
"""
from pathlib import Path
import itertools, json
import uharfbuzz as hb
import freetype
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONT = ROOT / 'firmware/fonts/Sarabun-Regular.ttf'
SIZES = (12, 14, 16, 18, 22)
MARKS = [0xE31, *range(0xE34, 0xE3B), *range(0xE47, 0xE4F)]

def shape(text):
    b = hb.Buffer(); b.add_str(text); b.guess_segment_properties()
    hb.shape(font, b, {'kern': False})
    x = 0; out = []
    for g, p in zip(b.glyph_infos, b.glyph_positions):
        out.append((g.codepoint, x + p.x_offset, p.y_offset))
        x += p.x_advance
    return tuple(out), x

def key(s):
    a = [ord(c) & 255 for c in s] + [0] * (4-len(s))
    return (a[0]<<24) | (a[1]<<16) | (a[2]<<8) | a[3]

def emit_array(f, typ, name, values, per=12):
    f.write(f'const {typ} {name}[] PROGMEM = {{\n')
    for i in range(0, len(values), per):
        f.write('  '+','.join(values[i:i+per])+',\n')
    f.write('};\n')

if __name__ == '__main__':
    face = hb.Face(FONT.read_bytes()); font = hb.Font(face)
    font.scale = (face.upem, face.upem); hb.ot_font_set_funcs(font)
    # All Thai letters plus all single marks and every standard vowel/tone
    # combination, including stacked marks, descenders and SARA AM.
    clusters = {chr(cp) for cp in range(0xE01, 0xE5C)}
    vowels = [0xE31, *range(0xE34,0xE3A)]
    tones = list(range(0xE48,0xE4D))
    for base in range(0xE01, 0xE2F):
        for m in MARKS + [0xE33]: clusters.add(chr(base)+chr(m))
        for a,b in itertools.product(vowels, tones):
            clusters.add(chr(base)+chr(a)+chr(b))
        for tone in tones:
            clusters.add(chr(base)+chr(tone)+chr(0xE33))
        # Canonical decomposed AM and explicitly reordered input are supported.
        for tone in [None]+tones:
            for seq in ([0xE4D,0xE32], [0xE4D,tone,0xE32] if tone else []):
                if seq: clusters.add(chr(base)+''.join(chr(c) for c in seq))
    # Also capture uncommon real-world clusters from project content.
    import re
    for path in [*ROOT.glob('sdcard/**/*.md'), *ROOT.glob('sdcard/**/*.txt'),
                 *ROOT.glob('sdcard/**/*.tsv'), *ROOT.glob('firmware/src/*.*')]:
        for m in re.finditer('[\u0e01-\u0e2e][\u0e31\u0e34-\u0e3a\u0e47-\u0e4e]{1,2}\u0e33?', path.read_text('utf-8',errors='ignore')):
            if len(m[0]) <= 4: clusters.add(m[0])
    cmap = TTFont(FONT).getBestCmap()
    cps = sorted(cp for cp in cmap if cp < 0x250 or 0xE00 <= cp < 0xE80 or cp in (0x200B,0x2013,0x2014,0x2018,0x2019,0x201C,0x201D,0x2022,0x2026,0x2032,0x2033,0x2190,0x2192,0x2264,0x2265,0xFEFF))
    gids = {0}; runs = []; entries = []; dedup = {}
    for s in sorted(clusters, key=key):
        run, advance = shape(s); gids.update(g[0] for g in run)
        if run not in dedup: dedup[run] = len(runs); runs.extend(run)
        entries.append((key(s),dedup[run],len(run),advance))
    mapping = []
    for cp in cps:
        run, advance = shape(chr(cp)); gids.add(run[0][0])
        mapping.append((cp,run[0][0],advance))
    gids = sorted(gids); gidmap = {g:i for i,g in enumerate(gids)}
    out = ROOT/'firmware/src/generated/thai_font_data.cpp'
    with out.open('w',encoding='utf-8',newline='\n') as f:
        f.write('// Generated by scripts/build_thai_font.py; Sarabun SIL OFL 1.1.\n#include "../thai_font_data.h"\n')
        emit_array(f,'ThaiRunGlyph','thaiRuns',[f'{{{gidmap[g]},{x},{y}}}' for g,x,y in runs],5)
        emit_array(f,'ThaiShape','thaiShapes',[f'{{0x{k:08x},{off},{adv},{n}}}' for k,off,n,adv in entries],3)
        emit_array(f,'ThaiCodepoint','thaiCodepoints',[f'{{{cp},{gidmap[g]},{adv}}}' for cp,g,adv in mapping],5)
        f.write(f'const uint32_t thaiShapeCount={len(entries)}, thaiCodepointCount={len(mapping)};\n')
        ft = freetype.Face(str(FONT)); atlas_info=[]
        for sz in SIZES:
            ft.set_pixel_sizes(0,sz); pixels=[]; glyphs=[]
            for gid in gids:
                ft.load_glyph(gid, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_NORMAL)
                b = ft.glyph.bitmap; offset=len(pixels); rowbytes=(b.width+1)//2
                for y in range(b.rows):
                    for x in range(0,b.width,2):
                        a=(b.buffer[y*b.pitch+x]+8)//17
                        c=(b.buffer[y*b.pitch+x+1]+8)//17 if x+1<b.width else 0
                        pixels.append((min(15,a)<<4)|min(15,c))
                glyphs.append((offset,b.width,b.rows,ft.glyph.bitmap_left,ft.glyph.bitmap_top))
            emit_array(f,'uint8_t',f'thaiPixels{sz}',[str(v) for v in pixels],32)
            emit_array(f,'ThaiBitmap',f'thaiGlyphs{sz}',[f'{{{o},{w},{h},{x},{y}}}' for o,w,h,x,y in glyphs],4)
            # A single baseline/cell includes the tallest Thai stack at this size.
            above=max(g[4] for g in glyphs); below=max(g[2]-g[4] for g in glyphs)
            for gid,_,dy in runs:
                _,_,gh,_,top=glyphs[gidmap[gid]]
                shifted=top+round(dy*sz/face.upem)
                above=max(above,shifted);below=max(below,gh-shifted)
            atlas_info.append((sz,above+1,above+below+2,len(pixels)))
        f.write('const ThaiAtlas thaiAtlases[] = {\n')
        for sz,baseline,height,_ in atlas_info:
            f.write(f'  {{thaiPixels{sz},thaiGlyphs{sz},{sz},{baseline},{height}}},\n')
        f.write('};\n')
    report={'upem':face.upem,'shapes':len(entries),'glyphs':len(gids),'runs':len(runs),'atlases':atlas_info,'source_bytes':out.stat().st_size}
    (ROOT/'.thai-work/font-report.json').write_text(json.dumps(report,indent=2))
    print(report)
